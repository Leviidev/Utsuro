#!/usr/bin/env python3
"""Turns WinDurango's d3d11_x.g.h into src/nt/d3d_generated.inc: every Xbox D3D11/DXGI
interface with its vtable flattened for one Era build (the dump's d3d11_x ABI), each method's
name, parameter count and the parameter that returns a new object."""
import re
import sys

HEADER = sys.argv[1]
OUT = sys.argv[2]
ABI = tuple(int(x) for x in sys.argv[3].split(".")) if len(sys.argv) > 3 else (6, 2, 11396, 0)

text = open(HEADER, encoding="utf-8", errors="replace").read()
lines = text.splitlines()


def abi_ok(req):
    if req is None:
        return None
    ok = True
    for op, a, b, c, d in re.findall(r"ABI\s*(>=|<)\s*abi_t\s*\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", req):
        v = (int(a), int(b), int(c), int(d))
        if op == ">=" and not ABI >= v:
            ok = False
        if op == "<" and not ABI < v:
            ok = False
    return ok


# interface -> list of (requires_ok_or_None, base, methods)
variants = {}
i = 0
req = None
while i < len(lines):
    ln = lines[i]
    m = re.search(r"requires\s*\(([^()]*)\)", ln)
    if re.search(r"\bstruct\b", ln) and not re.search(r"Vtbl", ln):
        req = None
    elif m:
        req = m.group(1)
    sm = re.search(r"\bstruct\s+(\w+)Vtbl(?:<ABI>)?\s*:\s*(?:\w+::)*(\w+)Vtbl<ABI>\s*$", ln) or \
        re.search(r"\bstruct\s+(\w+)Vtbl(?:<ABI>)?\s*:\s*(?:\w+::)*(\w+)Vtbl<ABI>", ln)
    if sm:
        name, base = sm.group(1), sm.group(2)
        # Body: from the next "{" to the matching "};".
        j = i + 1
        while "{" not in lines[j]:
            j += 1
        body = []
        j += 1
        while not lines[j].strip().startswith("};"):
            body.append(lines[j])
            j += 1
        joined = " ".join(b.strip() for b in body)
        methods = []
        for mm in re.finditer(r"([\w:<>\s\*&]+?)\(\*(\w+)\)\(void\s*\*\s*(?:,([^;]*))?\)\s*;", joined):
            ret, mname, params = mm.group(1).strip(), mm.group(2), mm.group(3) or ""
            plist = []
            depth = 0
            cur = ""
            for ch in params:
                if ch in "<(":
                    depth += 1
                if ch in ">)":
                    depth -= 1
                if ch == "," and depth == 0:
                    plist.append(cur.strip())
                    cur = ""
                else:
                    cur += ch
            if cur.strip():
                plist.append(cur.strip())
            out_idx, out_type = -1, ""
            for k, p in enumerate(plist):
                pm = re.search(r"(?:\w+::)*(\w+)(?:<ABI>)?\s*\*\*\s*(\w+)", p)
                if pm:
                    out_idx, out_type = k, pm.group(1)
            methods.append((mname, len(plist), out_idx, out_type, ret.split()[-1] if ret else "void"))
        variants.setdefault(name, []).append((abi_ok(req), base, methods))
        req = None
        i = j
    elif ln.strip().startswith("};") or ln.strip() == "":
        pass
    i += 1


def pick(name):
    best = None
    for ok, base, methods in variants.get(name, []):
        if ok is True:
            best = (base, methods)
    if best is None:
        for ok, base, methods in variants.get(name, []):
            if ok is None:
                best = (base, methods)
    return best


def flatten(name):
    p = pick(name)
    if p is None:
        return []
    base, methods = p
    if base == "IGraphicsUnknown":
        return list(methods)
    return flatten(base) + list(methods)


uuids = {}
for mm in re.finditer(r"DECLARE_ABI_UUIDOF_HELPER\((?:\w+::)*(\w+),\s*([^)]*)\)", text):
    nums = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", mm.group(2))]
    if len(nums) == 12:
        nums = nums[:2] + [(nums[2] << 8) | nums[3]] + nums[4:]
    if len(nums) != 11:
        continue
    a, b, c = nums[:3]
    d = nums[3:]
    uuids[mm.group(1)] = "%08X-%04X-%04X-%02X%02X-%02X%02X%02X%02X%02X%02X" % (a, b, c, *d)

# The DLL's own IID_* exports are authoritative (the header repeats a few GUIDs by mistake).
if len(sys.argv) > 4:
    import pefile, uuid
    pe = pefile.PE(sys.argv[4], fast_load=True)
    pe.parse_data_directories([pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    for sym in pe.DIRECTORY_ENTRY_EXPORT.symbols:
        if sym.name and sym.name.startswith(b"IID_"):
            n = sym.name[4:].decode()
            uuids[n] = str(uuid.UUID(bytes_le=pe.get_data(sym.address, 16))).upper()
seen = {}
for n, u in uuids.items():
    if n in variants and u in seen:
        print("warning: %s and %s share %s" % (n, seen[u], u), file=sys.stderr)
    seen[u] = n

# argv[5]: the table's name for a further ABI (no type declarations then; the first table has them).
TABLE = sys.argv[5] if len(sys.argv) > 5 else "kD3dIfaces"
with open(OUT, "w") as f:
    f.write("// Generated by tools/gen_d3d.py from WinDurango's d3d11_x.g.h for ABI %s. Do not edit.\n" % ".".join(map(str, ABI)))
    if len(sys.argv) <= 5:
        f.write("struct D3dMethodDef { const char* name; int params; int out_index; const char* out_type; };\n")
        f.write("struct D3dIfaceDef { const char* name; const char* iid; const char* base; std::vector<D3dMethodDef> methods; };\n")
    f.write("static const std::vector<D3dIfaceDef> %s = {\n" % TABLE)
    n = 0
    for name in sorted(variants):
        if name not in uuids:
            continue
        ms = flatten(name)
        if not ms:
            continue
        p = pick(name)
        f.write('    {"%s", "%s", "%s", {\n' % (name, uuids[name], p[0]))
        for (mn, pc, oi, ot, rt) in ms:
            f.write('        {"%s", %d, %d, "%s"},\n' % (mn, pc, oi, ot))
        f.write("    }},\n")
        n += 1
    f.write("};\n")
print("%d interfaces, %d uuids" % (n, len(uuids)), file=sys.stderr)
